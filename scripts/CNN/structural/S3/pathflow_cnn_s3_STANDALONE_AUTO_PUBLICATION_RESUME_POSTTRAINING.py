    sizes=[C*H*W for C,H,W in layer_shapes]; offsets=np.cumsum([0]+sizes[:-1]).astype(np.int64); n_nodes=int(sum(sizes))
    us=[];vs=[];flows=[];enr=[]
    def nid(layer,c,y,x):
        C,H,W=layer_shapes[layer]; return int(offsets[layer]+(c*H+y)*W+x)
    for l,(conv,E0) in enumerate(zip(model.convs,state["occurrence_flow"])):
        E=np.asarray(E0,float); cout,cin,k,_,Hout,Wout=E.shape; nocc=E.size
