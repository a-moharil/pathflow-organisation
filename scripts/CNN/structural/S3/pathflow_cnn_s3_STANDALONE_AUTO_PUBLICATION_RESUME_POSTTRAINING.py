def environment_vector(d):
    one=[1.0 if str(d["teacher_family"])==f else 0.0 for f in TEACHER_FAMILIES]
    q=(float(d["informative_fraction"])-QINFO_RANGE[0])/(QINFO_RANGE[1]-QINFO_RANGE[0])
