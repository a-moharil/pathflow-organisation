    ls=(math.log(float(d["snr"]))-math.log(SNR_RANGE[0]))/(math.log(SNR_RANGE[1])-math.log(SNR_RANGE[0]))
    return np.asarray(one+[q,r,ls,float(d["interaction_strength"]),float(d["localization"])],float)

