def train_run(env,arch,seed,opt_name,lr,splits=None):
    rid=s3_run_id(str(env.env_id),str(arch.arch_id),seed,opt_name)
    if RESUME and run_complete(rid): return
    owns_splits = splits is None
    if splits is None: splits,_=environment_dataset(env.to_dict())
    Xtr,ytr=splits["train"]; Xv,yv=splits["val"]; Xt,yt=splits["test"]
    model,_=build_model(arch,seed,False); init,scales,digest=native_initial_state(arch,seed); model.load_state_dict(init,strict=True); opt=make_optimizer(opt_name,model,lr)
    meta=base_meta(env,arch,seed,opt_name,lr,rid,digest)
    bundle={"version":S3_VERSION,"profile":PROFILE,"initialization_source":"S3_native_architecture_seed_only","initial_parameter_digest":digest,"states":{0:clone_state_dict_cpu(model)},"calibration_scales":scales}
    states_rows=[record_state_row(model,0,meta)]; history_rows=[{**meta,"epoch":0,"train_mse":np.nan,"val_mse":eval_mse(model,Xv,yv),"test_mse":eval_mse(model,Xt,yt)}]
    start_epoch=1; start_batch=0; partial_sum=0.; partial_count=0; rp=s3_resume(rid)
    if rp.exists() and RESUME:
        rs=trusted_torch_load(rp)
        if str(rs.get("version",""))!=S3_VERSION or str(rs.get("profile",""))!=PROFILE: raise RuntimeError(f"Stale resume file: {rp}")
        model.load_state_dict(rs["model_state"]); opt.load_state_dict(rs["optimizer_state"])
        for ost in opt.state.values():
            for k,v in list(ost.items()):
                if torch.is_tensor(v): ost[k]=v.to(DEVICE)
        start_epoch=int(rs["current_epoch"]); start_batch=int(rs["next_batch"]); partial_sum=float(rs["loss_sum"]); partial_count=int(rs["loss_count"]); states_rows=rs["states_rows"]; history_rows=rs["history_rows"]; bundle=rs["bundle"]
    for epoch in range(start_epoch,FULL_EPOCHS+1):
        model.train(); ss=partial_sum if epoch==start_epoch else 0.; nn_=partial_count if epoch==start_epoch else 0; first=start_batch if epoch==start_epoch else 0
        for bi,ids in enumerate(deterministic_batches(len(Xtr),epoch-1,seed,BATCH_SIZE)):
            if bi<first: continue
            if Xtr.device.type=="cuda": ids_t=torch.as_tensor(ids,device=DEVICE); xb=Xtr.index_select(0,ids_t); yb=ytr.index_select(0,ids_t)
            else: xb=Xtr[ids].to(DEVICE); yb=ytr[ids].to(DEVICE)
            opt.zero_grad(set_to_none=True); loss=F.mse_loss(model(xb),yb)
            if not torch.isfinite(loss):
                _write_divergence(rid,meta,epoch,bi,float(loss.detach().cpu()) if torch.isfinite(loss.detach()).item() else np.nan,states_rows,history_rows,bundle); return
            loss.backward(); opt.step(); ss+=float(loss.item()); nn_+=1
            if stop_requested(): save_resume(rid,model,opt,epoch,bi+1,ss,nn_,states_rows,history_rows,bundle); return
        if epoch in STATE_GRID:
            state_row=record_state_row(model,epoch,meta)
            if not np.isfinite(float(state_row.get("entropy_deficit",np.nan))):
                _write_divergence(rid,meta,epoch,-1,float("nan"),states_rows,history_rows,bundle); return
            states_rows=[r for r in states_rows if int(r["epoch"])!=epoch]+[state_row]
            history_rows=[r for r in history_rows if int(r["epoch"])!=epoch]+[{**meta,"epoch":epoch,"train_mse":ss/max(nn_,1),"val_mse":eval_mse(model,Xv,yv),"test_mse":eval_mse(model,Xt,yt)}]
            bundle["states"][epoch]=clone_state_dict_cpu(model); atomic_torch_save(bundle,s3_bundle(rid)); atomic_csv(pd.DataFrame(states_rows).sort_values("epoch"),s3_part(rid,"states")); atomic_csv(pd.DataFrame(history_rows).sort_values("epoch"),s3_part(rid,"history"))
        if epoch%RESUME_EVERY_EPOCHS==0 or epoch in STATE_GRID: save_resume(rid,model,opt,epoch+1,0,0.,0,states_rows,history_rows,bundle)
        start_batch=0; partial_sum=0.; partial_count=0
    h=pd.DataFrame(history_rows); q=h[np.isfinite(pd.to_numeric(h.val_mse,errors="coerce"))]
    best=q.loc[q.val_mse.astype(float).idxmin()]; last=q.sort_values("epoch").iloc[-1]
    atomic_csv(pd.DataFrame([{**meta,"diverged":False,"best_val_epoch":int(best.epoch),"best_val_mse":float(best.val_mse),"test_at_best_val":float(best.test_mse),"final_test_mse":float(last.test_mse)}]),s3_part(rid,"summary"))
    try: rp.unlink()
    except Exception: pass
    del model,opt
    if owns_splits: del splits
    if torch.cuda.is_available(): torch.cuda.empty_cache()

