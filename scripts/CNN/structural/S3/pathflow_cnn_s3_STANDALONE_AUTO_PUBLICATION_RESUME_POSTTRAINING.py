def make_optimizer(name,model,lr):
    if name=="adam": return torch.optim.Adam(model.parameters(),lr=lr,weight_decay=0.)
    if name=="rmsprop": return torch.optim.RMSprop(model.parameters(),lr=lr,alpha=.99,eps=1e-8,momentum=0.,weight_decay=0.)
    if name=="sgdm": return torch.optim.SGD(model.parameters(),lr=lr,momentum=.9,nesterov=False,weight_decay=0.)
    if name=="sgd": return torch.optim.SGD(model.parameters(),lr=lr,momentum=0.,nesterov=False,weight_decay=0.)
    raise ValueError(name)

def calibration_panel(panel,envs):
    ap=_maximin_rows(panel,["depth","parameter_count","execution_nodes","receptive_field","mean_hidden_width","hidden_width_cv"],min(CAL_ARCH_N,len(panel)))
    # Outcome-blind maximin over environment coordinates.
    V=np.stack([environment_vector(r.to_dict()) for _,r in envs.iterrows()]); med=np.median(V,axis=0); sc=np.median(np.abs(V-med),axis=0); sc=np.where(sc>1e-12,sc,1.); Z=(V-med)/sc
    chosen=[int(np.argmax(np.linalg.norm(Z-Z.mean(0),axis=1)))] if len(envs) else []
    while len(chosen)<min(CAL_ENV_N,len(envs)):
        d=np.min(np.stack([np.linalg.norm(Z-Z[j],axis=1) for j in chosen]),axis=0); d[chosen]=-np.inf; chosen.append(int(np.argmax(d)))
    ep=envs.iloc[chosen].copy(); atomic_csv(ap,OUTDIR/"calibration"/"calibration_architectures.csv"); atomic_csv(ep,OUTDIR/"calibration"/"calibration_environments.csv"); return ap,ep

def calibrate_learning_rates(panel,envs):
    path=OUTDIR/"calibration"/"optimizer_learning_rates.csv"
    if path.exists() and RESUME:
        d=safe_read_csv(path)
        if not d.empty and set(d.s3_version.astype(str))=={S3_VERSION} and set(d.profile.astype(str))=={PROFILE}:
            return {str(r.optimizer):float(r.learning_rate) for _,r in d.iterrows()}
    if SHARDS>1: raise RuntimeError("Run MODE=calibrate once with PATHFLOW_CNN_S3_SHARDS=1 before array jobs")
    archs,es=calibration_panel(panel,envs); chosen={"adam":ADAM_LR}; detail=[]
    # Generate each calibration environment once per process. The original implementation regenerated
    # identical datasets for every architecture and candidate LR, which was needlessly expensive on HPC.
    cal_env_cache={str(e.env_id):environment_dataset(e.to_dict())[0] for _,e in es.iterrows()}
    for opt_name in ["rmsprop","sgdm","sgd"]:
        candidates=[]
        for lr in LR_GRIDS[opt_name]:
            cell_scores=[]; ndiv=0
            for _,e in es.iterrows():
                splits=cal_env_cache[str(e.env_id)]; Xtr,ytr=splits["train"]
                for _,a in archs.iterrows():
                    model,_=build_model(a,0,False); init,scales,digest=native_initial_state(a,0); model.load_state_dict(init,strict=True)
                    initial_loss=eval_mse(model,Xtr,ytr); opt=make_optimizer(opt_name,model,float(lr)); checkpoints=[]; diverged=False
                    for epoch in range(1,CAL_EPOCHS+1):
                        model.train(); ss=0.; nn_=0
                        for ids in deterministic_batches(len(Xtr),epoch-1,0,BATCH_SIZE):
                            if Xtr.device.type=="cuda": ids_t=torch.as_tensor(ids,device=DEVICE); xb=Xtr.index_select(0,ids_t); yb=ytr.index_select(0,ids_t)
                            else: xb=Xtr[ids].to(DEVICE); yb=ytr[ids].to(DEVICE)
                            opt.zero_grad(set_to_none=True); loss=F.mse_loss(model(xb),yb)
                            if not torch.isfinite(loss): diverged=True; break
                            loss.backward(); opt.step(); ss+=float(loss.item()); nn_+=1
                        if diverged: break
                        if epoch in CAL_CHECKPOINTS: checkpoints.append(ss/max(nn_,1))
                    if diverged or not checkpoints or not np.isfinite(initial_loss) or initial_loss<=0:
                        score=50.0; ndiv+=1
                    else:
                        score=float(np.mean(np.log(np.clip(np.asarray(checkpoints,float),1e-30,None)/initial_loss)))
                    cell_scores.append(score); detail.append({"s3_version":S3_VERSION,"profile":PROFILE,"optimizer":opt_name,"learning_rate":lr,"env_id":str(e.env_id),"arch_id":str(a.arch_id),"initial_train_mse":initial_loss,"normalized_log_auc_score":score,"diverged":diverged,"initial_parameter_digest":digest})
                    del model,opt
                if torch.cuda.is_available(): torch.cuda.empty_cache()
            arr=np.asarray(cell_scores,float); med=float(np.median(arr)); q90=float(np.quantile(arr,.90)); objective=.70*med+.30*q90+5.0*ndiv/max(len(arr),1)
            candidates.append((objective,float(lr),med,q90,ndiv))
        candidates.sort(key=lambda z:(z[0],z[1])); chosen[opt_name]=candidates[0][1]
    out=pd.DataFrame([{"s3_version":S3_VERSION,"profile":PROFILE,"optimizer":o,"learning_rate":chosen[o],
                       "selection_rule":"S2 operating point locked" if o=="adam" else "global outcome-blind-to-structure training-loss calibration"} for o in OPTIMIZERS])
    atomic_csv(out,path); atomic_csv(pd.DataFrame(detail),OUTDIR/"calibration"/"learning_rate_calibration_detail.csv"); return chosen

