        {"env_id":"S3E_CAN_DISTRIBUTED","teacher_family":"deep_compositional","informative_fraction":.85,"spatial_correlation":.20,"snr":25.,"interaction_strength":.35,"localization":.05,"stage":"standalone_anchor","source_index":-2},
