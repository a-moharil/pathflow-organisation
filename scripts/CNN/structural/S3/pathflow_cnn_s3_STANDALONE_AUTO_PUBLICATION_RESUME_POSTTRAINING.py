def _progress_line(stage,done,total,t0,last_note=""):
    elapsed=max(time.perf_counter()-t0,1e-9); rate=done/elapsed if done else 0.0
    eta=(total-done)/rate if rate>0 else float("nan")
    eta_txt=(f"{eta/3600:.2f} h" if np.isfinite(eta) else "?")
    print(f"[{stage}] {done}/{total} ({100*done/max(total,1):.1f}%) | elapsed={elapsed/3600:.2f} h | ETA={eta_txt}{last_note}",flush=True)

def run_geometry_resume(panel,manifest,sentinel_ids):
    jobs=manifest[manifest.full_shard==SHARD_INDEX].copy(); jobs=jobs.head(MAX_RUNS) if MAX_RUNS>0 else jobs
    pidx=panel.set_index(panel.arch_id.astype(str),drop=False); sent=set(map(str,sentinel_ids))
    work=[]
    for _,r in jobs.iterrows():
        rid=s3_run_id(str(r.env_id),str(r.arch_id),int(r.seed_index),str(r.optimizer))
        if _summary_diverged(rid) or not s3_bundle(rid).exists(): continue
        done=_geometry_done_epochs(rid)
        grid=DENSE_SENTINEL_GEOMETRY_GRID if str(r.arch_id) in sent else GEOMETRY_GRID
        miss=[ep for ep in grid if ep not in done]
        if miss: work.append((r,miss))
    total=sum(len(m) for _,m in work); completed=0; t0=time.perf_counter()
    print(f"[geometry-resume] missing geometry units on shard {SHARD_INDEX}/{SHARDS}: {total}",flush=True)
    if total==0: return
    for r,missing_epochs in work:
        if stop_requested(): break
        rid=s3_run_id(str(r.env_id),str(r.arch_id),int(r.seed_index),str(r.optimizer))
        try:
            gp=s3_geometry_part(rid); sp=s3_geometry_scales_part(rid)
            old=safe_read_csv(gp) if RESUME else pd.DataFrame(); oldsc=safe_read_csv(sp) if RESUME else pd.DataFrame()
            rows=old.to_dict("records") if not old.empty else []; scrows=oldsc.to_dict("records") if not oldsc.empty else []
            for ep in missing_epochs:
                # Remove a half-written copy, if any, then recompute the scientific unit once.
                rows=[z for z in rows if int(float(z.get("epoch",-999999)))!=int(ep)]
                scrows=[z for z in scrows if int(float(z.get("epoch",-999999)))!=int(ep)]
                model,_=build_model(pidx.loc[str(r.arch_id)],int(r.seed_index),False)
                model.load_state_dict(load_state_for_run(r,ep)); st=cnn_structural_state(model,True); gs,gsc=analyze_execution_geometry(model,st)
                rec={"run_id":rid,"env_id":str(r.env_id),"arch_id":str(r.arch_id),"seed_index":int(r.seed_index),"optimizer":str(r.optimizer),"epoch":ep,**gs}
                rows.append(rec)
                if not gsc.empty:
                    z=gsc.copy()
                    for k,v in rec.items(): z[k]=v
                    scrows.extend(z.to_dict("records"))
                atomic_csv(pd.DataFrame(rows),gp); atomic_csv(pd.DataFrame(scrows),sp)
                del model; completed+=1
                if completed==1 or completed%20==0 or completed==total:
                    _progress_line("geometry-resume",completed,total,t0,f" | last={rid}@E{ep:03d}")
                if stop_requested(): break
            if stop_requested(): break
        except Exception as exc:
            atomic_json({"run_id":rid,"exception":traceback.format_exc()},OUTDIR/"audit"/f"GEOMETRY_RESUME_EXCEPTION__{int(r.full_index):06d}.json")
            print(f"[geometry-resume] run failed but resume continues: {type(exc).__name__}: {exc}",flush=True)
    atomic_json({"shard_index":SHARD_INDEX,"shards":SHARDS,"missing_at_start":total,"computed_this_invocation":completed,"stop_requested":stop_requested()},OUTDIR/"audit"/f"GEOMETRY_RESUME_SHARD_{SHARD_INDEX:04d}.json")

def run_dynamics_resume(panel,manifest):
    jobs=manifest[manifest.full_shard==SHARD_INDEX].copy(); jobs=jobs.head(MAX_RUNS) if MAX_RUNS>0 else jobs
    pidx=panel.set_index(panel.arch_id.astype(str),drop=False)
    expected_pairs=list(zip(STATE_GRID[:-1],STATE_GRID[1:])); work=[]
    for _,r in jobs.iterrows():
        rid=s3_run_id(str(r.env_id),str(r.arch_id),int(r.seed_index),str(r.optimizer))
        if _summary_diverged(rid) or not s3_bundle(rid).exists(): continue
        p=s3_dynamics_part(rid); old=safe_read_csv(p) if RESUME else pd.DataFrame(); done=set()
        if not old.empty and {"t0","t1"}.issubset(old.columns):
            for a,b in zip(pd.to_numeric(old.t0,errors="coerce"),pd.to_numeric(old.t1,errors="coerce")):
                if np.isfinite(a) and np.isfinite(b): done.add((int(a),int(b)))
        miss=[pair for pair in expected_pairs if pair not in done]
        if miss: work.append((r,miss))
    total=sum(len(m) for _,m in work); completed=0; tstart=time.perf_counter()
    print(f"[dynamics-resume] missing interval units on shard {SHARD_INDEX}/{SHARDS}: {total}",flush=True)
    if total==0: return
    for r,missing_pairs in work:
        if stop_requested(): break
        rid=s3_run_id(str(r.env_id),str(r.arch_id),int(r.seed_index),str(r.optimizer)); p=s3_dynamics_part(rid)
        try:
            old=safe_read_csv(p) if RESUME else pd.DataFrame(); rowmap={}
            if not old.empty and {"t0","t1"}.issubset(old.columns):
                for rec in old.to_dict("records"):
                    try: rowmap[(int(rec["t0"]),int(rec["t1"]))]=rec
                    except Exception: pass
            tau=0.0; arch=pidx.loc[str(r.arch_id)]
            for t0,t1 in expected_pairs:
                pair=(t0,t1)
                if pair in rowmap:
                    tau+=float(rowmap[pair].get("Jeffreys",0.0)); continue
                m0,_=build_model(arch,int(r.seed_index),False); m1,_=build_model(arch,int(r.seed_index),False)
                m0.load_state_dict(load_state_for_run(r,t0)); m1.load_state_dict(load_state_for_run(r,t1))
                s0=cnn_structural_state(m0,True); s1=cnn_structural_state(m1,True); d=exact_interval_dynamics(m0,s0,m1,s1); tau+=d["Jeffreys"]
                rec={"run_id":rid,"env_id":str(r.env_id),"arch_id":str(r.arch_id),"seed_index":int(r.seed_index),"optimizer":str(r.optimizer),"t0":t0,"t1":t1,"tau_J":tau,**d}
                rowmap[pair]=rec
                ordered=[rowmap[pair2] for pair2 in expected_pairs if pair2 in rowmap]
                atomic_csv(pd.DataFrame(ordered),p)
                del m0,m1; completed+=1
                if completed==1 or completed%50==0 or completed==total:
                    _progress_line("dynamics-resume",completed,total,tstart,f" | last={rid}:{t0}->{t1}")
                if stop_requested(): break
            if stop_requested(): break
        except Exception as exc:
            atomic_json({"run_id":rid,"exception":traceback.format_exc()},OUTDIR/"audit"/f"DYNAMICS_RESUME_EXCEPTION__{int(r.full_index):06d}.json")
            print(f"[dynamics-resume] run failed but resume continues: {type(exc).__name__}: {exc}",flush=True)
    atomic_json({"shard_index":SHARD_INDEX,"shards":SHARDS,"missing_at_start":total,"computed_this_invocation":completed,"stop_requested":stop_requested()},OUTDIR/"audit"/f"DYNAMICS_RESUME_SHARD_{SHARD_INDEX:04d}.json")

def _resume_post_training(panel,envs,sentinel_ids,manifest):
    if START_FRESH:
        raise RuntimeError("This is a resume executable. PATHFLOW_CNN_S3_START_FRESH=1 is forbidden.")
    lr=_resume_lr_map(manifest); write_manifest(panel,envs,sentinel_ids,lr)
    audit=post_training_resume_audit(manifest,sentinel_ids,True)
    print(
        f"[resume-audit] training_missing={len(audit['training_missing'])} | bundle_missing={len(audit['bundle_missing'])} | "
        f"geometry={audit['geometry_done']}/{audit['geometry_expected']} (missing {audit['geometry_missing']}) | "
        f"dynamics={audit['dynamics_done']}/{audit['dynamics_expected']} (missing {audit['dynamics_missing']})",flush=True
    )
    if audit["training_missing"] or audit["bundle_missing"]:
        raise RuntimeError(
            "Post-training resume requires completed Stage-1 trajectories and their checkpoint bundles. "
            f"training_missing={len(audit['training_missing'])}, bundle_missing={len(audit['bundle_missing'])}; "
            "see audit/post_training_resume_audit.csv"
        )
    banner("CNN-S3 RESUME STAGE 2/4 — BCANw GEOMETRY (MISSING UNITS ONLY)")
    run_geometry_resume(panel,manifest,sentinel_ids)
    audit=post_training_resume_audit(manifest,sentinel_ids,True)
    if stop_requested():
        write_artifact_inventory(); maybe_requeue("post-training geometry resume safely paused"); return
    if audit["geometry_missing"]:
        raise RuntimeError(f"Geometry resume ended with {audit['geometry_missing']} units still missing; inspect audit and rerun the same command.")
    banner("CNN-S3 RESUME STAGE 3/4 — PATH-SPACE DYNAMICS (MISSING INTERVALS ONLY)")
    run_dynamics_resume(panel,manifest)
    audit=post_training_resume_audit(manifest,sentinel_ids,True)
    if stop_requested():
        write_artifact_inventory(); maybe_requeue("post-training dynamics resume safely paused"); return
    if audit["dynamics_missing"]:
        raise RuntimeError(f"Dynamics resume ended with {audit['dynamics_missing']} intervals still missing; inspect audit and rerun the same command.")
    banner("CNN-S3 RESUME STAGE 4/4 — AGGREGATION / STATISTICS / FIGURES / PDF")
    return _finish_campaign(panel,envs,manifest,sentinel_ids,lr)

def main():
    _autodetect_slurm_wall_hours()
    if MODE=="resume_post_training" and START_FRESH:
        raise RuntimeError("Resume mode refuses PATHFLOW_CNN_S3_START_FRESH=1 before touching the existing campaign output.")
    if MODE!="resume_post_training":
        maybe_clean_output()
    ensure_runtime_notes()
    panel,envs,sentinel_ids=build_panels()
    manifest=create_manifest(panel,envs)
    write_manifest(panel,envs,sentinel_ids,None)

    # Mandatory gate: any preflight failure raises before calibration or training starts.
    run_preflight(panel,envs)
    if MODE=="preflight":
        write_artifact_inventory(); return
    if MODE=="resume_post_training":
        return _resume_post_training(panel,envs,sentinel_ids,manifest)
    if MODE=="autopilot":
        return _autopilot(panel,envs,sentinel_ids,manifest)
    if MODE=="calibrate":
        lr=calibrate_learning_rates(panel,envs); write_manifest(panel,envs,sentinel_ids,lr); write_artifact_inventory(); print("Frozen learning rates:",lr,flush=True); return
    if MODE=="all":
        if SHARDS!=1: raise RuntimeError("MODE=all requires SHARDS=1")
        return _autopilot(panel,envs,sentinel_ids,manifest)

    lr=load_learning_rates(); write_manifest(panel,envs,sentinel_ids,lr)
    if MODE=="train":
        run_training(panel,envs,manifest,lr); campaign_completeness(manifest,sentinel_ids,False,False); write_artifact_inventory()
    elif MODE=="geometry":
        run_geometry(panel,manifest,sentinel_ids); campaign_completeness(manifest,sentinel_ids,True,False); write_artifact_inventory()
    elif MODE=="dynamics":
        run_dynamics(panel,manifest); campaign_completeness(manifest,sentinel_ids,False,True); write_artifact_inventory()
    elif MODE=="aggregate":
        return _finish_campaign(panel,envs,manifest,sentinel_ids,lr)

