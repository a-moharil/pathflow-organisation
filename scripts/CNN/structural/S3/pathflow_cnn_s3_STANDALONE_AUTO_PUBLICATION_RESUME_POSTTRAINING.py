def _global_normalize(a):
    dims=tuple(range(1,a.ndim)); s=a.sum(dim=dims); shape=[a.shape[0]]+[1]*(a.ndim-1)
    good=torch.isfinite(s)&(s>0)
    out=torch.where(good.reshape(shape),a/torch.clamp(s,min=EPS).reshape(shape),torch.zeros_like(a))
    return out,s

@torch.no_grad()
def cnn_log_partition(model,source_sq,response_sq,q):
    a=torch.pow(torch.clamp(source_sq.to(DEVICE,dtype=torch.float64),min=0.),float(q)); a,s=_global_normalize(a)
    valid=torch.isfinite(s)&(s>0); logscale=torch.where(valid,torch.log(torch.clamp(s,min=EPS)),torch.full_like(s,-torch.inf))
    for l,conv in enumerate(model.convs):
        a=F.conv2d(a,torch.pow(torch.square(conv.weight.to(torch.float64)),float(q)),bias=None,stride=1,padding=0)
        if l<len(model.convs)-1: a=a*torch.pow(torch.clamp(response_sq[l].to(DEVICE,dtype=torch.float64),min=0.),float(q))
        a,sl=_global_normalize(a); good=valid&torch.isfinite(sl)&(sl>0)
        logscale=torch.where(good,logscale+torch.log(torch.clamp(sl,min=EPS)),torch.full_like(logscale,-torch.inf)); valid=good
    h,w=model.spatial_shapes()[-1]; return torch.where(valid,logscale+math.log((1.0/(h*w))**(2.0*float(q))),torch.full_like(logscale,-torch.inf))

def cnn_topological_log_count(model):
    h,w=model.spatial_shapes()[-1]; logn=math.log(float(model.channels[-1]*h*w))
    for conv in model.convs: logn+=math.log(float(conv.in_channels*conv.kernel_size[0]*conv.kernel_size[1]))
    return float(logn)

def _entropy_prob(p,dims):
    return -torch.where(p>0,p*torch.log(torch.clamp(p,min=PATH_LOG_FLOOR)),torch.zeros_like(p)).sum(dim=dims)

@torch.no_grad()
def cnn_factor_state(model,source_sq,response_sq,return_flows=True):
    source_sq=source_sq.to(DEVICE,dtype=torch.float64); response_sq=[r.to(DEVICE,dtype=torch.float64) for r in response_sq]
    B=source_sq.shape[0]; logZ1=cnn_log_partition(model,source_sq,response_sq,1.0); logZ2=cnn_log_partition(model,source_sq,response_sq,2.0)
    valid=torch.isfinite(logZ1)
    alpha=[]; a,_=_global_normalize(source_sq); alpha.append(a)
    for l,conv in enumerate(model.convs):
        a=F.conv2d(a,torch.square(conv.weight.to(torch.float64)),bias=None,stride=1,padding=0)
        if l<len(model.convs)-1: a=a*response_sq[l]
        a,_=_global_normalize(a); alpha.append(a)
    beta=[None]*(len(model.convs)+1); b=torch.ones_like(alpha[-1],dtype=torch.float64); b,_=_global_normalize(b); beta[-1]=b
    for l in range(len(model.convs)-1,-1,-1):
        target=beta[l+1]
        if l<len(model.convs)-1: target=target*response_sq[l]
        b=F.conv_transpose2d(target,torch.square(model.convs[l].weight.to(torch.float64)),bias=None,stride=1,padding=0); b,_=_global_normalize(b); beta[l]=b
    node_flow=[]
    for l in range(len(alpha)):
        v=alpha[l]*beta[l]; v,_=_global_normalize(v); node_flow.append(v)
    occurrence=[]; param=[]; layer_metrics=[]; elog_edges=torch.zeros(B,dtype=torch.float64,device=DEVICE)
    max_occ=torch.zeros(B,dtype=torch.float64,device=DEVICE); max_push=torch.zeros(B,dtype=torch.float64,device=DEVICE)
    for l,conv in enumerate(model.convs):
        k=int(conv.kernel_size[0]); cout=conv.out_channels; cin=conv.in_channels
        patches=F.unfold(alpha[l],kernel_size=k,stride=1,padding=0); Hout,Wout=alpha[l+1].shape[-2:]; L=Hout*Wout
        target=beta[l+1]
        if l<len(model.convs)-1: target=target*response_sq[l]
        target=target.reshape(B,cout,L); w2=torch.square(conv.weight.to(torch.float64)).reshape(cout,cin*k*k)
        E=target[:,:,None,:]*w2[None,:,:,None]*patches[:,None,:,:]; den=E.sum(dim=(1,2,3)); good=den>0
        E=torch.where(good[:,None,None,None],E/torch.clamp(den[:,None,None,None],min=EPS),torch.zeros_like(E))
        E=E.reshape(B,cout,cin,k,k,Hout,Wout); P=E.sum(dim=(-1,-2)); occurrence.append(E); param.append(P)
        occsum=E.sum(dim=(1,2,3,4,5,6)); psum=P.sum(dim=(1,2,3,4)); max_occ=torch.maximum(max_occ,torch.abs(occsum-1)); max_push=torch.maximum(max_push,torch.abs(psum-occsum))
        logw=torch.log(torch.clamp(torch.square(conv.weight.to(torch.float64)),min=PATH_LOG_FLOOR)); logfactor=logw[None,:,:,:,:,None,None]
        if l<len(model.convs)-1: logfactor=logfactor+torch.log(torch.clamp(response_sq[l],min=PATH_LOG_FLOOR))[:, :, None, None, None, :, :]
        elog_edges+=torch.sum(torch.where(E>0,E*logfactor,torch.zeros_like(E)),dim=(1,2,3,4,5,6))
        Hocc=_entropy_prob(E,(1,2,3,4,5,6)); Hparam=_entropy_prob(P,(1,2,3,4)); Pb=P[...,None,None]
        ratio=torch.where(E>0,E/torch.clamp(Pb,min=PATH_LOG_FLOOR),torch.ones_like(E)); Hreuse_direct=-torch.sum(torch.where(E>0,E*torch.log(torch.clamp(ratio,min=PATH_LOG_FLOOR)),torch.zeros_like(E)),dim=(1,2,3,4,5,6))
        Hreuse=Hocc-Hparam; ntheta=cout*cin*k*k; m=Hout*Wout; nocc=ntheta*m
        Socc=math.log(nocc)-Hocc; Sparam=math.log(ntheta)-Hparam; Sreuse=math.log(m)-Hreuse
        eta_occ=torch.exp(torch.clamp(-Socc,min=-745,max=0)); eta_param=torch.exp(torch.clamp(-Sparam,min=-745,max=0)); eta_reuse=torch.exp(torch.clamp(-Sreuse,min=-745,max=0))
        of=E.reshape(B,-1); pf=P.reshape(B,-1)
        layer_metrics.append({"H_occ":Hocc,"H_param":Hparam,"H_reuse":Hreuse,"S_occ":Socc,"S_param":Sparam,"S_reuse":Sreuse,
                              "eta1_occ":eta_occ,"eta1_param":eta_param,"eta1_reuse":eta_reuse,
                              "occurrence_cv":of.std(1,unbiased=False)/torch.clamp(of.mean(1),min=EPS),
                              "parameter_cv":pf.std(1,unbiased=False)/torch.clamp(pf.mean(1),min=EPS),
                              "entropy_identity_residual":Hocc-Hparam-Hreuse_direct,"deficit_identity_residual":Socc-Sparam-Sreuse,
                              "eta_factorization_residual":eta_occ-eta_param*eta_reuse})
    p0=node_flow[0]; elogsource=torch.sum(torch.where(p0>0,p0*torch.log(torch.clamp(source_sq,min=PATH_LOG_FLOOR)),torch.zeros_like(p0)),dim=(1,2,3))
    h,w=model.spatial_shapes()[-1]; H=logZ1-(elogsource+elog_edges+math.log((1.0/(h*w))**2)); logN=cnn_topological_log_count(model)
    Sdef=logN-H; logeta1=H-logN; logeta2=2*logZ1-logZ2-logN
    def arr(x):
        y=x.detach().cpu().numpy().astype(float); y[~valid.detach().cpu().numpy()]=np.nan; return y
    return {"valid":valid.detach().cpu().numpy().astype(bool),"logZ1":arr(logZ1),"logZ2":arr(logZ2),"S_path":arr(H),"entropy_deficit":arr(Sdef),
            "eta1":arr(torch.exp(torch.clamp(logeta1,min=-745,max=0))),"eta2":arr(torch.exp(torch.clamp(logeta2,min=-745,max=0))),
            "node_flow":[v.detach().cpu().numpy() for v in node_flow] if return_flows else [],"occurrence_flow":[e.detach().cpu().numpy() for e in occurrence] if return_flows else [],
            "parameter_flow":[p.detach().cpu().numpy() for p in param] if return_flows else [],"layer_metrics":[{k:arr(v) for k,v in d.items()} for d in layer_metrics],
            "occurrence_conservation_error":arr(max_occ),"pushforward_conservation_error":arr(max_push)}

@torch.no_grad()
def cnn_structural_state(model,return_flows=True):
    source=torch.ones((1,INPUT_CHANNELS,model.resolution,model.resolution),dtype=torch.float64,device=DEVICE); responses=[]; shapes=model.spatial_shapes()
    for l,conv in enumerate(model.convs[:-1]):
        h,w=shapes[l+1]; responses.append(torch.ones((1,conv.out_channels,h,w),dtype=torch.float64,device=DEVICE))
    st=cnn_factor_state(model,source,responses,return_flows=return_flows)
    hidden=list(range(max(len(model.convs)-1,0)))
    out={"logZ1":float(st["logZ1"][0]),"logZ2":float(st["logZ2"][0]),"S_path":float(st["S_path"][0]),"entropy_deficit":float(st["entropy_deficit"][0]),"eta1":float(st["eta1"][0]),"eta2":float(st["eta2"][0]),
         "occurrence_conservation_error":float(st["occurrence_conservation_error"][0]),"pushforward_conservation_error":float(st["pushforward_conservation_error"][0])}
    for key in ["S_occ","S_param","S_reuse","eta1_occ","eta1_param","eta1_reuse","occurrence_cv","parameter_cv"]:
        vals=[float(st["layer_metrics"][l][key][0]) for l in hidden]; out[f"hidden_mean_{key}"]=float(np.mean(vals)) if vals else np.nan
    out["max_entropy_identity_residual"]=float(max(abs(d["entropy_identity_residual"][0]) for d in st["layer_metrics"])); out["max_deficit_identity_residual"]=float(max(abs(d["deficit_identity_residual"][0]) for d in st["layer_metrics"])); out["max_eta_factorization_residual"]=float(max(abs(d["eta_factorization_residual"][0]) for d in st["layer_metrics"]))
    if return_flows:
        out.update({"node_flow":[v[0] for v in st["node_flow"]],"occurrence_flow":[e[0] for e in st["occurrence_flow"]],"parameter_flow":[p[0] for p in st["parameter_flow"]],"layer_metrics":[{k:float(v[0]) for k,v in d.items()} for d in st["layer_metrics"]]})
    return out

