def exact_interval_dynamics(model0,st0,model1,st1):
    E0G=0.; E1G=0.; varproxy=0.; sqdisp=0.; npar=0
    for c0,c1,P0,P1 in zip(model0.convs,model1.convs,st0["parameter_flow"],st1["parameter_flow"]):
        raw0=c0.weight.detach().cpu().numpy().astype(np.float64); raw1=c1.weight.detach().cpu().numpy().astype(np.float64)
        w0=np.square(raw0); w1=np.square(raw1); dlog=np.log(np.clip(w1,PATH_LOG_FLOOR,None))-np.log(np.clip(w0,PATH_LOG_FLOOR,None))
        p0=np.asarray(P0,float); p1=np.asarray(P1,float); mu0=float(np.sum(p0*dlog)); mu1=float(np.sum(p1*dlog)); E0G+=mu0; E1G+=mu1
        varproxy+=float(np.sum(p0*(dlog-mu0)**2)); sqdisp+=float(np.sum((raw1-raw0)**2)); npar+=raw0.size
    logM=float(st1["logZ1"]-st0["logZ1"]); kl01=max(0.,logM-E0G); kl10=max(0.,E1G-logM); J=max(0.,E1G-E0G)
    return {"E_p0_G":E0G,"E_p1_G":E1G,"log_mgf":logM,"KL_p0_p1":kl01,"KL_p1_p0":kl10,"Jeffreys":J,
            "parameter_marginal_G_variance_proxy":varproxy,"parameter_squared_displacement":sqdisp,"parameter_rms_displacement":math.sqrt(sqdisp/max(npar,1)),"Jeffreys_per_parameter_sq_displacement":J/max(sqdisp,EPS)}

