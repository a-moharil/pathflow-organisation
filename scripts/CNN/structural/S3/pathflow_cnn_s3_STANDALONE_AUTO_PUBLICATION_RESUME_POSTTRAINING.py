def _resume_lr_map(manifest):
    """Recover the already-frozen learning rates without recalibrating or retraining."""
    try:
        return load_learning_rates()
    except Exception as exc:
        found={o:set() for o in OPTIMIZERS}
        for _,r in manifest.iterrows():
            o=str(r.optimizer)
            if len(found[o])>1:
                continue
            rid=s3_run_id(str(r.env_id),str(r.arch_id),int(r.seed_index),o)
            for kind in ["summary","states","history"]:
                q=safe_read_csv(s3_part(rid,kind))
                if not q.empty and "learning_rate" in q.columns:
                    vals=pd.to_numeric(q.learning_rate,errors="coerce").dropna().unique()
                    for v in vals: found[o].add(float(v))
                    break
            if all(len(found[x])>=1 for x in OPTIMIZERS):
                break
        bad={o:sorted(v) for o,v in found.items() if len(v)!=1}
        if bad:
            raise RuntimeError(
                "Could not recover one unique frozen learning rate per optimizer from the completed S3 run. "
                f"Calibration load error was {type(exc).__name__}: {exc}; recovered={found}"
            )
        out={o:next(iter(found[o])) for o in OPTIMIZERS}
        print(f"[resume] calibration CSV unavailable; recovered frozen learning rates from completed run metadata: {out}",flush=True)
        return out

