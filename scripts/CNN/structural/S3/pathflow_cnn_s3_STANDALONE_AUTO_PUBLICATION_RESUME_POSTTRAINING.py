def architecture_descriptors(hidden,kernels):
    ch=[INPUT_CHANNELS]+list(map(int,hidden))+[1]; h=w=RESOLUTION; occ=mac=0; nodes=INPUT_CHANNELS*h*w; rf=1
    for cin,cout,k in zip(ch[:-1],ch[1:],kernels):
        h=h-int(k)+1; w=w-int(k)+1
        if h<1 or w<1: return {"valid":False}
        z=int(cout*cin*k*k*h*w); occ+=z; mac+=z; nodes+=int(cout*h*w); rf+=int(k)-1
    params=sum(int(cout*cin*k*k) for cin,cout,k in zip(ch[:-1],ch[1:],kernels))
    hw=np.asarray(hidden,float) if len(hidden) else np.asarray([1.])
    return {"valid":bool(h>=MIN_FINAL_RESOLUTION and nodes<=MAX_EXEC_NODES),"depth":len(kernels),"parameter_count":int(params),
            "occurrence_count":int(occ),"macs":int(mac),"execution_nodes":int(nodes),"receptive_field":int(rf),
            "output_resolution":int(h),"mean_hidden_width":float(hw.mean()),"max_hidden_width":int(hw.max()),
            "hidden_width_cv":float(hw.std()/max(hw.mean(),EPS))}

