def holm_adjust(pvals):
    p=np.asarray(pvals,float); out=np.full(len(p),np.nan); idx=np.where(np.isfinite(p))[0]
    if not len(idx): return out
    order=idx[np.argsort(p[idx])]; run=0.; m=len(order)
    for rank,j in enumerate(order):
        run=max(run,min(1.,(m-rank)*float(p[j]))); out[j]=run
    return out

def safe_friedman(arrays):
    arr=[np.asarray(a,float) for a in arrays]
    if not arr or any(len(a)==0 for a in arr): return np.nan,np.nan
    M=np.stack(arr,axis=1)
    if np.all(np.nanmax(M,axis=1)-np.nanmin(M,axis=1) <= 1e-15):
        return 0.0,1.0
    with warnings.catch_warnings():
        warnings.simplefilter("ignore",RuntimeWarning)
        chi,p=friedmanchisquare(*arr)
    if not np.isfinite(chi) or not np.isfinite(p):
        return np.nan,np.nan
    return float(chi),float(p)

