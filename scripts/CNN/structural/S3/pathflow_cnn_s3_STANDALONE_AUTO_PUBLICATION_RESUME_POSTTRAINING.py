class ActivationModule(nn.Module):
    def __init__(self,name): super().__init__(); self.name=str(name).lower()
    def forward(self,x):
        if self.name=="relu": return F.relu(x)
        if self.name=="tanh": return torch.tanh(x)
        if self.name=="silu": return F.silu(x)
        if self.name=="identity": return x
        raise ValueError(self.name)

class ConvTraceNet(nn.Module):
    def __init__(self,resolution,hidden_channels,kernel_sizes,activation,seed):
        super().__init__(); self.resolution=int(resolution)
        self.hidden_channels=[int(x) for x in hidden_channels]; self.kernel_sizes=[int(k) for k in kernel_sizes]
        self.activation_name=str(activation).lower(); self.activation=ActivationModule(self.activation_name)
        self.channels=[INPUT_CHANNELS]+self.hidden_channels+[1]
        self.convs=nn.ModuleList(); torch.manual_seed(int(seed))
        for cin,cout,k in zip(self.channels[:-1],self.channels[1:],self.kernel_sizes):
            self.convs.append(nn.Conv2d(cin,cout,kernel_size=k,stride=1,padding=0,bias=False))
        self.reset_common_directions(seed)
    def reset_common_directions(self,seed):
        g=torch.Generator(device="cpu").manual_seed(int(seed))
        with torch.no_grad():
            for conv in self.convs:
                W=torch.randn(conv.weight.shape,generator=g,dtype=conv.weight.dtype)
                W/=math.sqrt(max(conv.in_channels*conv.kernel_size[0]*conv.kernel_size[1],1)); conv.weight.copy_(W)
    def spatial_shapes(self):
        h=w=self.resolution; out=[(h,w)]
        for k in self.kernel_sizes: h=h-k+1; w=w-k+1; out.append((h,w))
        return out
    def output_resolution(self): return int(self.spatial_shapes()[-1][0])
    def parameter_count(self): return int(sum(p.numel() for p in self.parameters()))
    def forward(self,x):
        h=x
        for l,conv in enumerate(self.convs):
            z=conv(h); h=self.activation(z) if l<len(self.convs)-1 else z
        return h.mean(dim=(-1,-2))

@torch.no_grad()
def calibrate_initial_signal(model,Xcal,target_var=1.0):
    model.eval(); h=Xcal.to(DEVICE); scales=[]
    for l,conv in enumerate(model.convs):
        z=conv(h)
        if l<len(model.convs)-1:
            sd=float(torch.std(z,unbiased=False).item())
            scale=float(np.clip(math.sqrt(target_var)/max(sd,1e-6),.15,6.0))
            conv.weight.mul_(scale); z=conv(h); h=model.activation(z); scales.append(scale)
        else: scales.append(1.0)
    return scales

