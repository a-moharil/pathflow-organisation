def _parse_slurm_duration_to_hours(value):
    """Parse Slurm TimeLimit values such as 48:00:00 or 2-00:00:00."""
    if value is None:
        return 0.0
    v=str(value).strip()
    if not v or v.upper() in {"UNLIMITED","INFINITE","N/A"}:
        return 0.0
    try:
        days=0
        if "-" in v:
            ds,v=v.split("-",1); days=int(ds)
        parts=[int(float(x)) for x in v.split(":")]
        if len(parts)==3:
            h,m,sec=parts
        elif len(parts)==2:
            h,m,sec=0,parts[0],parts[1]
        elif len(parts)==1:
            h,m,sec=0,parts[0],0
        else:
            return 0.0
        return days*24.0+h+m/60.0+sec/3600.0
    except Exception:
        return 0.0


def _autodetect_slurm_wall_hours():
    """Use Slurm's allocated time limit automatically unless the user supplied a soft limit."""
    global SOFT_WALL_HOURS
    if SOFT_WALL_HOURS>0 or not SLURM_JOB_ID or shutil.which("scontrol") is None:
        return
    try:
        cp=subprocess.run(["scontrol","show","job",SLURM_JOB_ID,"-o"],capture_output=True,text=True,timeout=15,check=True)
        m=re.search(r"(?:^|\s)TimeLimit=([^\s]+)",cp.stdout)
        if m:
            h=_parse_slurm_duration_to_hours(m.group(1))
            if h>0:
                SOFT_WALL_HOURS=h
                print(f"[slurm] TimeLimit={m.group(1)} detected; S3 will stop safely {SOFT_STOP_BUFFER_MIN:.0f} min before allocation end.",flush=True)
    except Exception as exc:
        print(f"[slurm] wall-time autodetection unavailable ({type(exc).__name__}: {exc}); explicit signals/resume remain active.",flush=True)


